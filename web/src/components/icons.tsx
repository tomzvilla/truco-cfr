export type GlyphName = keyof typeof GLYPHS;

export function PixelIcon({ name, size = 24 }: { name: GlyphName; size?: number }) {
  const rows = GLYPHS[name];
  const rects: string[] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === '#') rects.push(`M${x} ${y}h1v1h-1z`);
  });
  return (
    <svg
      className="picon"
      width={size}
      height={size}
      viewBox="0 0 12 12"
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
    >
      <path d={rects.join('')} fill="currentColor" />
    </svg>
  );
}
